#!/usr/bin/env bash
# setup-ollama-jetson.sh
# Writes a systemd override for Ollama on Jetson (Orin) with GPU, memory and
# JIT-cache settings, then restarts the service and checks GPU discovery.
#
# Usage:
#   sudo ./setup-ollama-jetson.sh [options]
#
# Options:
#   --ctx N              Context length            (default: 32768)
#   --keep-alive VAL     e.g. 5m, 30m, -1 (forever) (default: 5m)
#   --host ADDR:PORT     Bind address              (default: 127.0.0.1:11434)
#   --models-dir PATH    Model store, e.g. on NVMe (default: unchanged)
#   --kv-cache TYPE      f16 | q8_0 | q4_0          (default: q4_0)
#   --no-flash-attn      Disable flash attention
#   --dry-run            Print the override, change nothing
#   -h | --help          Show this help
#
# Anything in the override can be tweaked afterwards with:
#   sudo systemctl edit ollama.service

set -euo pipefail

CTX=16384
KEEP_ALIVE="5m"
HOST="127.0.0.1:11434"
MODELS_DIR=""
KV_CACHE="q4_0"
FLASH_ATTN=1
DRY_RUN=0

TMP_OVERRIDE="$(mktemp)"
trap 'rm -f "$TMP_OVERRIDE"' EXIT

OLLAMA_LIB="/usr/local/lib/ollama"
DROPIN_DIR="/etc/systemd/system/ollama.service.d"
DROPIN="${DROPIN_DIR}/override.conf"

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mWARN:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

usage() { sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'; exit 0; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --ctx)           CTX="$2"; shift 2 ;;
    --keep-alive)    KEEP_ALIVE="$2"; shift 2 ;;
    --host)          HOST="$2"; shift 2 ;;
    --models-dir)    MODELS_DIR="$2"; shift 2 ;;
    --kv-cache)      KV_CACHE="$2"; shift 2 ;;
    --no-flash-attn) FLASH_ATTN=0; shift ;;
    --dry-run)       DRY_RUN=1; shift ;;
    -h|--help)       usage ;;
    *) die "Unknown option: $1 (try --help)" ;;
  esac
done

[[ "$CTX" =~ ^[0-9]+$ ]] || die "--ctx must be an integer"
case "$KV_CACHE" in f16|q8_0|q4_0) ;; *) die "--kv-cache must be f16, q8_0 or q4_0" ;; esac
if [[ "$KV_CACHE" != "f16" && "$FLASH_ATTN" -eq 0 ]]; then
  warn "Quantised KV cache needs flash attention; Ollama will fall back to f16."
fi

[[ $DRY_RUN -eq 1 || $EUID -eq 0 ]] || die "Run with sudo (or use --dry-run)."

# --- Detect platform -------------------------------------------------------
[[ -f /etc/nv_tegra_release ]] || die "/etc/nv_tegra_release not found - is this a Jetson?"
L4T_MAJOR="$(head -n1 /etc/nv_tegra_release | sed -n 's/^# R\([0-9]\+\).*/\1/p')"
[[ -n "$L4T_MAJOR" ]] || die "Could not parse L4T version from /etc/nv_tegra_release"
log "Detected L4T R${L4T_MAJOR}"

command -v ollama >/dev/null || die "ollama not installed. Run: curl -fsSL https://ollama.com/install.sh | sh"
[[ -d "$OLLAMA_LIB" ]] || die "$OLLAMA_LIB not found - unexpected Ollama install layout."

# Pick the CUDA backend directory that matches the JetPack generation.
CUDA_DIR=""
case "$L4T_MAJOR" in
  36) for d in cuda_jetpack6 cuda_v12; do [[ -d "$OLLAMA_LIB/$d" ]] && { CUDA_DIR="$d"; break; }; done ;;
  3[7-9]|4[0-9]) for d in cuda_v13 cuda_jetpack7; do [[ -d "$OLLAMA_LIB/$d" ]] && { CUDA_DIR="$d"; break; }; done ;;
  35) for d in cuda_jetpack5 cuda_v11; do [[ -d "$OLLAMA_LIB/$d" ]] && { CUDA_DIR="$d"; break; }; done ;;
  *) warn "Untested L4T R${L4T_MAJOR}" ;;
esac

if [[ -z "$CUDA_DIR" ]]; then
  warn "No matching CUDA backend found in $OLLAMA_LIB. Available:"
  ls -1 "$OLLAMA_LIB" | sed 's/^/    /' >&2
  die "Update Ollama, or edit CUDA_DIR selection in this script."
fi
log "Using CUDA backend: $OLLAMA_LIB/$CUDA_DIR"

LD_PATH="$OLLAMA_LIB:$OLLAMA_LIB/$CUDA_DIR"
[[ -d /usr/local/cuda/lib64 ]] && LD_PATH="$LD_PATH:/usr/local/cuda/lib64"

# Ollama service user's home holds the CUDA JIT cache.
OLLAMA_HOME="$(getent passwd ollama | cut -d: -f6 || true)"
[[ -n "$OLLAMA_HOME" ]] || OLLAMA_HOME="/usr/share/ollama"
JIT_CACHE="$OLLAMA_HOME/.nv/ComputeCache"

# --- Build override --------------------------------------------------------
{
  echo "# Generated by setup-ollama-jetson.sh on $(date -Iseconds)"
  echo "[Service]"
  echo "Environment=\"OLLAMA_HOST=$HOST\""
  echo "Environment=\"OLLAMA_CONTEXT_LENGTH=$CTX\""
  echo "Environment=\"OLLAMA_KEEP_ALIVE=$KEEP_ALIVE\""
  echo "Environment=\"OLLAMA_MAX_LOADED_MODELS=1\""
  echo "Environment=\"OLLAMA_NUM_PARALLEL=1\""
  echo "Environment=\"OLLAMA_FLASH_ATTENTION=$FLASH_ATTN\""
  echo "Environment=\"OLLAMA_KV_CACHE_TYPE=$KV_CACHE\""
  echo "Environment=\"LD_LIBRARY_PATH=$LD_PATH\""
  echo "Environment=\"CUDA_CACHE_PATH=$JIT_CACHE\""
  echo "Environment=\"CUDA_CACHE_MAXSIZE=4294967296\""
  if [[ "$L4T_MAJOR" -ge 37 ]]; then
    echo "# JetPack 7.x: force iGPU discovery and the CUDA 13 backend"
    echo "Environment=\"OLLAMA_IGPU_ENABLE=1\""
    echo "Environment=\"GGML_BACKEND_PATH=$OLLAMA_LIB/$CUDA_DIR/libggml-cuda.so\""
  else
    echo "Environment=\"JETSON_JETPACK=$([[ $L4T_MAJOR -eq 35 ]] && echo 5 || echo 6)\""
  fi
  [[ -n "$MODELS_DIR" ]] && echo "Environment=\"OLLAMA_MODELS=$MODELS_DIR\""
} > "$TMP_OVERRIDE"

if [[ $DRY_RUN -eq 1 ]]; then
  log "Dry run - would write $DROPIN:"
  cat "$TMP_OVERRIDE"
  rm -f "$TMP_OVERRIDE"
  exit 0
fi

# --- Apply -----------------------------------------------------------------
mkdir -p "$DROPIN_DIR"
if [[ -f "$DROPIN" ]]; then
  BACKUP="$DROPIN.bak.$(date +%Y%m%d-%H%M%S)"
  cp "$DROPIN" "$BACKUP"
  log "Backed up existing override to $BACKUP"
fi
install -m 0644 "$TMP_OVERRIDE" "$DROPIN"
rm -f "$TMP_OVERRIDE"
log "Wrote $DROPIN"

mkdir -p "$JIT_CACHE"
chown -R ollama:ollama "$OLLAMA_HOME/.nv"
log "CUDA JIT cache: $JIT_CACHE"

if [[ -n "$MODELS_DIR" ]]; then
  mkdir -p "$MODELS_DIR"
  chown -R ollama:ollama "$MODELS_DIR"
  log "Model store: $MODELS_DIR (owned by ollama)"
fi

systemctl daemon-reload
systemctl restart ollama
log "Restarted ollama, waiting for API..."

API="http://${HOST/0.0.0.0/127.0.0.1}"
for _ in $(seq 1 30); do
  curl -fs "$API/api/version" >/dev/null 2>&1 && break
  sleep 1
done
curl -fs "$API/api/version" >/dev/null 2>&1 || die "API did not come up. Check: journalctl -u ollama -b"

# --- Verify GPU discovery --------------------------------------------------
sleep 2
COMPUTE="$(journalctl -u ollama --since "-1min" --no-pager | grep -m1 'inference compute' || true)"
echo
if grep -q 'library=cpu' <<<"$COMPUTE"; then
  warn "Ollama is still on the CPU:"
  echo "    $COMPUTE"
  echo "    Next: re-run the Ollama installer to update, then this script again."
elif [[ -n "$COMPUTE" ]]; then
  log "GPU detected:"
  echo "    $COMPUTE"
else
  warn "No 'inference compute' line yet - check: journalctl -u ollama -b | grep -i compute"
fi

echo
log "Done. Test with:  ollama run gemma3:270m --verbose 'hi' && ollama ps"